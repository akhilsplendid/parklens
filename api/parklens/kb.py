"""Park knowledge base: animals and attractions extracted from the park's public pages.

Every item keeps its source URL so narration can cite it. The JSON file is generated by
scripts/extract_kb.py and is not committed (see README).
"""

from __future__ import annotations

import json
import re
import unicodedata
from dataclasses import dataclass, field
from pathlib import Path


def _fold(s: str) -> str:
    """Lowercase and strip accents so 'Amurtiger' matches 'amur tiger' and 'lodjur' 'Lodjur'."""
    s = unicodedata.normalize("NFKD", s.lower())
    return "".join(c for c in s if not unicodedata.combining(c))


@dataclass
class Item:
    id: str
    kind: str  # "animal" | "attraction"
    name: str
    text_sv: str
    source_url: str
    headings: list[str] = field(default_factory=list)
    image: str | None = None
    scientific_name: str | None = None
    height_requirement: str | None = None
    min_height_cm: int | None = None
    min_age: int | None = None
    solo_min_height_cm: int | None = None
    solo_min_age: int | None = None
    lat: float | None = None
    lon: float | None = None

    @property
    def short_name(self) -> str:
        """'Wildfire på Kolmården' -> 'Wildfire'."""
        return re.sub(r"\s+(på|at)\s+\w+$", "", self.name, flags=re.I).strip()

    def facts(self, limit: int = 2500) -> str:
        return self.text_sv[:limit]


_AGE_RE = re.compile(r"(\d+)\s*år")
_SOLO_RE = re.compile(r"(?:minst?\s*)?(\d+)\s*cm(?:[^.]*?(\d+)\s*år)?[^.]*?utan\s+vux", re.I)
_NO_LIMIT_WITH_ADULT_RE = re.compile(r"ingen\s+längdgräns\s+i\s+vuxet", re.I)


def _derive_rules(raw: dict) -> dict:
    """Pull age and 'without adult' thresholds out of the Swedish rule text.

    Patterns seen on the park's pages:
      "Minst 120 cm"                                   -> min_height_cm
      "Barn från 100 cm och 4 år åker i vuxet sällskap" -> min_height_cm + min_age
      "Ingen längdgräns i vuxet sällskap, minst 110 cm & 5 år utan vuxen"
                                                       -> no limit with adult; solo 110 cm / 5 y
    """
    text = raw.get("height_requirement") or ""
    out: dict = {}
    solo = _SOLO_RE.search(text)
    if solo:
        out["solo_min_height_cm"] = int(solo.group(1))
        if solo.group(2):
            out["solo_min_age"] = int(solo.group(2))
    if _NO_LIMIT_WITH_ADULT_RE.search(text):
        out["min_height_cm"] = None
        out["min_age"] = None
        return out
    ages = [int(a) for a in _AGE_RE.findall(text) if int(a) < 15]  # 15 = adult companion age
    if ages:
        out["min_age"] = min(ages)
    return out


class KnowledgeBase:
    def __init__(self, items: list[Item], park: str = "Park"):
        self.park = park
        self.items = items
        self._by_id = {i.id: i for i in items}

    @classmethod
    def load(cls, path: Path) -> KnowledgeBase:
        data = json.loads(Path(path).read_text(encoding="utf-8"))
        items = []
        for raw in data["items"]:
            fields = {k: raw.get(k) for k in Item.__dataclass_fields__ if k in raw}
            fields.update(_derive_rules(raw))
            items.append(Item(**fields))
        return cls(items, park=data.get("park", "Park"))

    @property
    def animals(self) -> list[Item]:
        return [i for i in self.items if i.kind == "animal"]

    @property
    def attractions(self) -> list[Item]:
        return [i for i in self.items if i.kind == "attraction"]

    def get(self, item_id: str) -> Item | None:
        return self._by_id.get(item_id)

    def find(self, query: str) -> Item | None:
        """Best-effort match on id, name or scientific name."""
        q = _fold(query).strip()
        if not q:
            return None
        if q in self._by_id:
            return self._by_id[q]
        for i in self.items:
            if q in (_fold(i.short_name), _fold(i.name), _fold(i.scientific_name or "")):
                return i
        for i in self.items:
            if q in _fold(i.name) or (i.scientific_name and q in _fold(i.scientific_name)):
                return i
        return None

    def search(self, query: str, kind: str | None = None, limit: int = 5) -> list[Item]:
        """Keyword search over names and text, for interest matching ('big cats', 'apor')."""
        terms = [t for t in _fold(query).split() if len(t) > 2]
        scored = []
        for i in self.items:
            if kind and i.kind != kind:
                continue
            hay = _fold(f"{i.name} {i.scientific_name or ''} {' '.join(i.headings)} {i.text_sv}")
            score = sum(hay.count(t) for t in terms)
            if score:
                scored.append((score, i))
        scored.sort(key=lambda s: -s[0])
        return [i for _, i in scored[:limit]]

    def catalogue(self, kind: str | None = None) -> str:
        """Compact list the model can pick from, one per line."""
        rows = []
        for i in self.items:
            if kind and i.kind != kind:
                continue
            extra = f" ({i.scientific_name})" if i.scientific_name else ""
            rows.append(f"{i.id}: {i.short_name}{extra}")
        return "\n".join(rows)
